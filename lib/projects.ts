// Видео прикрепляется к посту по публичной ссылке: Meta скачивает его сама (MP4/MOV, H.264, до 5 минут, до 1 ГБ)
export type Media = { type: "VIDEO" | "IMAGE"; url: string };

// Картинка из игры для постов: что на ней (подсказка для текста и фактчека) и теги для подбора к теме
export type Picture = { url: string; about: string; tags: string[] };

export type Promo = { code: string; fact: string; until: string; rubrics: string[] }; // until — последний день, включительно (МСК)

export type Rubric = {
  id: string;
  weight: number;
  brief: string;
  media?: Media;
  topics?: string[];
  topicTag?: string; // своя тема Threads у рубрики вместо очереди проекта
  withPicture?: boolean; // прикладывать картинку из pictures проекта
  link?: (date: Date, content?: string) => string; // своя ссылка рубрики вместо ссылки проекта (например, мини-игра)
};

export type Project = {
  id: "oloid" | "buro";
  name: string;
  link: (date: Date, content?: string) => string; // ссылка с UTM; content — utm_content (аккаунт-рубрика)
  requireLink?: boolean; // ссылка обязательна в каждом посте (проверяется в ruleCheck)
  topicTags?: string[]; // темы Threads (одна на пост): берётся та, что дольше всех не использовалась
  voice: string;
  facts: string[];
  forbidden: string[];
  rubrics: Rubric[];
  alternateRubric?: string; // рубрика-посев (например, трейлер)
  alternateEveryDays?: number; // не чаще раза в N суток (72 часа × N/3) с прошлого поста этой рубрики; без поля — через пост
  promo?: Promo; // промокод: попадает в факты, пока действует, и только в разрешённые рубрики
  pictures?: Picture[]; // одобренные Ильёй кадры (public/media/), без спойлеров
  stopList?: RegExp[]; // штампы, которые отклоняются механически (вдобавок к общим запретам)
  seasonalHint?: (date: Date) => string | null;
};

// UTM: месяц в campaign, аккаунт и рубрика в content — видно в аналитике сайта, какие рубрики приводят людей
const utm = (base: string, d: Date, content?: string) =>
  `${base}?utm_source=threads&utm_medium=organic&utm_campaign=threads-${month(d)}${content ? `&utm_content=${content}` : ""}`;

const month = (d: Date) => `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, "0")}`;

