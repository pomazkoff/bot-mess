/** Промокод действует до конца дня until по Москве. */
export const promoActive = (p: Project, now = new Date()) =>
  !!p.promo && now.getTime() <= Date.parse(`${p.promo.until}T23:59:59+03:00`);

/** Факты проекта на сегодня: с промокодом, пока он действует. */
export const factsFor = (p: Project, now = new Date()) => (promoActive(p, now) ? [...p.facts, p.promo!.fact] : p.facts);

export function pickWeighted<T extends { weight: number }>(items: T[], exclude?: string, key?: (t: T) => string): T {
  const pool = exclude && key ? items.filter((i) => key(i) !== exclude) : items;
  const list = pool.length ? pool : items;
  const total = list.reduce((s, i) => s + i.weight, 0);
  let r = Math.random() * total;
  for (const i of list) if ((r -= i.weight) <= 0) return i;
  return list[list.length - 1];
}
