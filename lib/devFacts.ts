const PLAYTIME = /2\s*[–—-]\s*3\s*час|два\s*[–—-]?\s*три\s*час|2\s*или\s*3\s*час/iu;
const PRICE_WORD = /₽|(?<![\p{L}])руб(?:л\p{L}*|(?!\p{L}))|(?<![\p{L}])цен(?:а|у|ы|е)(?![\p{L}])/iu;
const HOUR_WORD = /(?<![\p{L}])час(?:а|ов|ы)?(?![\p{L}])/iu;

/** Числа как в факте: «0.9.28» целиком, «27,5» и «27.5» — одно и то же. Ссылки вырезаны. */
export function numberTokens(text: string): string[] {
  const noUrl = text.replace(/https?:\/\/\S+/g, " ");
  return (noUrl.match(/\d+(?:[.,]\d+)*/g) ?? []).map((token) => token.replace(/,/g, "."));
}

/**
 * Пост рубрики «цифры разработки»: каждое число есть в выбранном факте,
 * хотя бы одно число факта названо, цены и часов прохождения нет.
 */
export function devNumberProblem(text: string, fact: string): string | null {
  if (PLAYTIME.test(text)) return "часы прохождения в этот пост не входят: в списке цифр разработки их нет";
  const body = text.replace(/https?:\/\/\S+/g, " ");
  if (PRICE_WORD.test(body)) return "цену в посте цифр разработки не называть";
  if (HOUR_WORD.test(body) && !HOUR_WORD.test(fact)) return "часы в этом посте не из выбранного факта";
  const allowed = new Set(numberTokens(fact));
  const used = numberTokens(text);
  if (allowed.size && !used.some((token) => allowed.has(token))) return "в посте нет числа из выбранного факта";
  const extra = used.find((token) => !allowed.has(token));
  if (extra) return `число ${extra} не из выбранного факта`;
  return null;
}
